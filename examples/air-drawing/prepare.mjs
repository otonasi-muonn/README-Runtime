#!/usr/bin/env node
// Build step for the air-drawing card (run before asc, see readme-runtime.json):
// decode a real drawing with air-drawing-board's own decoder and write what the card needs.
//
//   upstream/tests/fixtures/test-vectors-v1.json  "sample-face" (encoded string, as saved by the app)
//     -> upstream/src/codec/drawingCodec.ts decodeDrawing()   (unchanged; bundled with esbuild,
//        run in Node because it is async and needs atob / Blob / DecompressionStream)
//     -> generated/drawing.json   strokes for demo.tsx
//     -> generated/drawing.ts     per-stroke constants for logic.ts (AssemblyScript)
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import assert from 'node:assert/strict';
import { build } from 'esbuild';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const CASE = 'sample-face';
const fixturePath = path.join(here, 'upstream/tests/fixtures/test-vectors-v1.json');
const codecPath = path.join(here, 'upstream/src/codec/drawingCodec.ts');

const bundled = await build({ entryPoints: [codecPath], bundle: true, write: false, format: 'esm', platform: 'neutral', logLevel: 'silent' });
const codec = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const fixture = JSON.parse(fs.readFileSync(fixturePath, 'utf8'));
const vector = fixture.validCases.find((c) => c.name === CASE);
if (!vector) throw new Error(`no valid case "${CASE}" in ${fixturePath}`);
const strokes = await codec.decodeDrawing(vector.encoded);
// the fixture states what a correct decoder must return; hold the real one to it
assert.deepEqual(strokes, vector.expectedDecoded, 'decodeDrawing() disagrees with expectedDecoded');
if (strokes.length !== 4) throw new Error(`logic.ts and demo.tsx are written for 4 strokes; "${CASE}" has ${strokes.length}`);

const outDir = path.join(here, 'generated');
fs.mkdirSync(outDir, { recursive: true });
const source = { fixture: 'upstream/tests/fixtures/test-vectors-v1.json', case: CASE, encoded: vector.encoded, decoder: 'upstream/src/codec/drawingCodec.ts decodeDrawing()' };
fs.writeFileSync(path.join(outDir, 'drawing.json'), `${JSON.stringify({ note: 'generated by prepare.mjs - do not edit', source, strokes })}\n`);

const lines = [
  `// generated by prepare.mjs from ${source.fixture} ("${CASE}"), decoded with ${source.decoder}. Do not edit.`,
  `export const STROKES: i32 = ${strokes.length};`,
  `export const TOTAL_POINTS: i32 = ${strokes.reduce((s, x) => s + x.pts.length, 0)};`,
  ...strokes.map((s, i) => `export const POINTS_${i}: i32 = ${s.pts.length}; export const COLOR_${i}: i32 = ${s.c}; export const WIDTH_${i}: i32 = ${s.w};`),
];
fs.writeFileSync(path.join(outDir, 'drawing.ts'), `${lines.join('\n')}\n`);
console.log(`prepare: decoded "${CASE}" (${vector.encoded.length} chars) -> ${strokes.length} strokes, ${strokes.map((s) => s.pts.length).join('+')} points`);
